#!/usr/bin/env python3
"""t2-DENOVO one-key pipeline (Phase E).

Pure de novo generation path for the BER102 (KRAS G4, 7X8M) pocket:
candidate isosteres (model products / docked library) -> rDock redock ->
aromatic-aware masked probe (P[S] gate) -> pose-scan endorsement ->
probability-endorsed N->S replacement (benzothiazole formation) ->
generic two-anchor seed placement -> seed-guided inpainting generation ->
t2 retrieval (SMILES equality; t2 is used ONLY here).

Compliance: no t2 topology/conformation/fragment enters any seed or
coordinate. The full t2 molecule is never constructed as an input; the
bridge CH2 is always generated by the model itself.

Stages (each callable separately):
  A1  select+redock isostere candidates            phaseA_select_dock.py
  A2  masked probe on redock poses (gate v1)       phaseA_probe.py
  A3  context probes (trimmed cores / pairs)       phaseA3_context_probe.py
  A4  bis-BM dimer assembly + redock + probe       phaseA4_dimer_dock.py + phaseA4_dimer_probe.py
  A5  berberine-referenced superposition probe     phaseA5_berref_probe.py
  A6  probe-guided rigid pose scan (gate v2)       phaseA6_posescan.py
  BC  N->S replacement + seed set (Phases B+C)     phaseBC_replacement_seed.py
  D   inpainting generation + t2 retrieval         phaseD_generate.py

Usage:
  python run_denovo.py --stage all
  python run_denovo.py --stage A1,A2,A6,BC
  python run_denovo.py --stage D --gpu 1 --rounds 16
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(os.path.dirname(HERE))  # rna2smol/


def run(cmd, gpu=None, log=None):
    env = dict(os.environ)
    if gpu is not None:
        env['CUDA_VISIBLE_DEVICES'] = str(gpu)
    print(f'\n===== {" ".join(cmd)} =====', flush=True)
    if log:
        with open(log, 'w') as f:
            r = subprocess.run(cmd, cwd=PROJ, env=env, stdout=f,
                               stderr=subprocess.STDOUT)
        if r.returncode != 0:
            sys.exit(f'[FATAL] stage failed, see {log}')
    else:
        subprocess.run(cmd, cwd=PROJ, env=env, check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--stage', default='all')
    ap.add_argument('--gpu', default='1')
    ap.add_argument('--rounds', type=int, default=16)
    ap.add_argument('--run-tag', default='D1')
    args = ap.parse_args()

    P = lambda s: os.path.join(HERE, s)
    py = sys.executable
    stages = args.stage.split(',') if args.stage != 'all' else ['A1', 'A2', 'A3', 'A4', 'A5', 'A6', 'BC', 'D']

    if 'A1' in stages:
        run([py, P('phaseA_select_dock.py'), '--n-runs', '10'], log=P('phaseA_select_dock.log'))
    if 'A2' in stages:
        run([py, P('phaseA_probe.py')], gpu=args.gpu, log=P('phaseA_probe.log'))
    if 'A3' in stages:
        run([py, P('phaseA3_context_probe.py')], gpu=args.gpu, log=P('phaseA3.log'))
    if 'A4' in stages:
        run([py, P('phaseA4_dimer_dock.py')], log=P('phaseA4_dock.log'))
        run([py, P('phaseA4_dimer_probe.py')], gpu=args.gpu, log=P('phaseA4_probe.log'))
    if 'A5' in stages:
        run([py, P('phaseA5_berref_probe.py')], gpu=args.gpu, log=P('phaseA5.log'))
    if 'A6' in stages:
        run([py, P('phaseA6_posescan.py')], gpu=args.gpu, log=P('phaseA6.log'))
    if 'BC' in stages:
        run([py, P('phaseBC_replacement_seed.py')], gpu=args.gpu, log=P('phaseBC.log'))
    if 'D' in stages:
        run([py, P('phaseD_generate.py'), '--run', args.run_tag,
             '--rounds', str(args.rounds)], gpu=args.gpu, log=P(f'run{args.run_tag}.log'))
    print('\n[pipeline] done.')


if __name__ == '__main__':
    main()
