#!/usr/bin/env python3
"""Phase F: masked element probe on the X1 BMZ-CH2-BMZ product (ring N sites).

For the de-novo X1 product c1ccc2[nH]c(Cc3nc4ccccc4[nH]3)nc2c1 (generated by
the model itself from two independent same-pocket fragments), probe each of
the four ring-nitrogen positions with a uniform belief (aromatic-aware,
t=1): P[S] decides whether the N->S ring conversion is endorsed
(gate > 10%). Probe on the raw generation pose first; the best pose is then
re-docked per the validated rDock protocol and re-probed.
"""
import sys, os, json, glob
import numpy as np
import torch
sys.path.insert(0, '/home/data/users/gaoletian/rna2smol')
os.chdir('/home/data/users/gaoletian/rna2smol')
import warnings; warnings.filterwarnings('ignore')
from rdkit import Chem, RDLogger
RDLogger.DisableLog('rdApp.*')
from util.ligand_code_util import parse_sdf_file, parse_pdb_file
from dataloader.featurizer import pocket_to_tensor, mol_to_tensor, ProteinLigandDataLoader
from util.mol_utils import MAP_ATOM_TYPE_AROMATIC_PDB_TO_INDEX as T2I, MAP_INDEX_TO_ATOM_TYPE_AROMATIC_PDB as I2T
sys.path.insert(0, 'casestudy/kras_g4/_archive_ber101_era')
from probe_element_prob import build_graphs  # noqa: E402  (hijacks cwd at import)
os.chdir('/home/data/users/gaoletian/rna2smol')
from accelerate import Accelerator
from model.bfn4edmol import Config, BFN4SBDDScoreModel
from genbypkt import load_compiled_model

K = 13
IDX_S = T2I[(16, True)]
POCKET = 'casestudy/kras_g4/ber102_rdock/ber102_pocket.pdb'
OUTJSON = 'casestudy/kras_g4/t2_denovo/phaseF_probe_results.json'

# pick one representative X1 product pose (canonical SMILES match)
TARGET_SMI = 'c1ccc2[nH]c(Cc3nc4ccccc4[nH]3)nc2c1'
poses = []
for m in Chem.SDMolSupplier('casestudy/kras_g4/t2_denovo/gen_runX1/valid_mols.sdf', removeHs=True):
    if m is None or not m.HasProp('_Name'):
        continue
    if Chem.MolToSmiles(m) == TARGET_SMI:
        poses.append(m)
print(f'[F] representative poses: {len(poses)}')
mol = poses[0]
mol.SetProp('_Name', 'X1_BMZ_CH2_BMZ_rep1')
POSE = os.environ.get('POSE_SDF', 'casestudy/kras_g4/t2_denovo/phaseF_input_pose.sdf')
w = Chem.SDWriter(POSE)
w.write(mol); w.close()

# ring N sites: the two pyrrolic [nH] and two pyridinic n of the benzimidazoles
BMZ = Chem.MolFromSmarts('c1ccc2[nH]cnc2c1')
BMZ2 = Chem.MolFromSmarts('c1ccc2nc[nH]c2c1')
mt = mol.GetSubstructMatches(BMZ) or mol.GetSubstructMatches(BMZ2)
assert mt, 'no benzimidazole match'
ring = list(mt[0])
Ns = [i for i in ring if mol.GetAtomWithIdx(i).GetSymbol() == 'N']
print(f'[F] ring N sites: {Ns}')

args_dict = {'config_file': 'config.yaml', 'exp_name': 't', 'revision': 'r',
             'debug': True, 'resume': False, 'wandb_resume_id': None,
             'empty_folder': False, 'test_only': True, 'seed': 42,
             'no_wandb': True, 'logging_level': 'warning', 'random_rot': False,
             'pos_noise_std': 0, 'pos_normalizer': 2.0, 'batch_size': 1,
             'epochs': 1, 'v_loss_weight': 1, 'lr': 1e-4, 'scheduler': 'plateau',
             'weight_decay': 0, 'max_grad_norm': 'Q', 'sigma1_coord': 0.03,
             'beta1': 1.5, 't_min': 1e-4, 'use_discrete_t': True,
             'discrete_steps': 1000, 'destination_prediction': True,
             'sampling_strategy': 'end_back_pmf', 'time_emb_mode': 'simple',
             'time_emb_dim': 1, 'pos_init_mode': 'zero', 'ckpt_path': 'best',
             'num_samples': 1, 'sample_steps': 100, 'sample_num_atoms': 'ref',
             'visual_chain': False, 'docking_mode': 'vina_score',
             'output_prefix': 't', 'feat_mode': 'generalfeat',
             'use_cavity_volume': False, 'volume_prob_table_path': None,
             'use_probabilistic': False, 'prob_top_n': 5, 'prob_beam_width': 100}
cfg = Config(**args_dict)
model = BFN4SBDDScoreModel(net_config=cfg.dynamics.net_config, protein_atom_feature_dim=11,
                           ligand_atom_feature_dim=13, time_emb_dim=1, ed_feature_dim=4)
acc = Accelerator(mixed_precision='bf16')
model.load_state_dict(load_compiled_model(
    model, torch.load('ckpt/onlypkt_ftwithrna_oncrossdocked_onlygeneralfeat_train_best_val_loss_step_111429.pth',
                      map_location='cpu')), strict=False)
model = acc.prepare(model); model.eval()
unwrapped = acc.unwrap_model(model)
beta1 = float(unwrapped.beta1)

pocket = parse_pdb_file(path=POCKET)
pocket_tensor = pocket_to_tensor(pocket, mode='general')
base = mol_to_tensor(parse_sdf_file(POSE, sanitize=False) if False else parse_sdf_file(POSE), mode='molcraft')
NATOMS = int(base['pos'].shape[0])

graphs, meta = [], []
for site in Ns:
    graphs.append(build_graphs(pocket_tensor, base))
    meta.append(site)

res = {}
loader = ProteinLigandDataLoader(graphs, batch_size=1, shuffle=False)
with torch.no_grad():
    for g_i, batch in enumerate(loader):
        site = meta[g_i]
        batch = batch.to(acc.device)
        bl = batch.mol_element_batch
        n = bl.shape[0]
        theta = torch.zeros((n, K), device=acc.device)
        ktrue = batch.mol_atom_feature.long()
        logits = torch.zeros((n, K), device=acc.device)
        logits[torch.arange(n, device=acc.device), ktrue] = beta1
        theta = torch.softmax(logits, -1)
        if site is not None:
            gi = np.where(bl.cpu().numpy() == 0)[0][site]
            theta[gi, :] = 1.0 / K
        t = torch.ones((n, 1), device=acc.device)
        gamma = 1 - 0.03 ** 2
        mu = batch.mol_pos * gamma / 2.0
        _, p0, _, _, _ = unwrapped.interdependency_modeling(
            time=t, pocket_pos=batch.pocket_pos / 2,
            pocket_v=batch.pocket_atom_feature.float(),
            batch_pocket=batch.pocket_element_batch,
            ed_pos=torch.empty((0, 3), device=acc.device),
            ed_v=torch.empty((0, 4), device=acc.device),
            batch_ed=batch.ed_ed_code_batch, batch_ligand=bl,
            theta_h_t=theta, mu_pos_t=mu,
            gamma_coord=torch.full((n, 1), gamma, device=acc.device),
            pocket_res=None, pocket_ele=None)
        probs = torch.softmax(torch.log(p0.clamp(min=1e-12)), -1)
        row = probs[np.where(bl.cpu().numpy() == 0)[0][site]] if site is not None else None
        if row is not None:
            top = row.argmax().item()
            res[str(site)] = {
                'element': mol.GetAtomWithIdx(site).GetSymbol(),
                'aromatic': bool(mol.GetAtomWithIdx(site).GetIsAromatic()),
                'PS_arom': round(float(row[IDX_S]), 4),
                'top1': f"{I2T[top][0]}{'*' if I2T[top][1] else ''}",
                'probs': [round(float(x), 5) for x in row],
            }
            print(f"[F] N{site} ({'pyrrolic' if mol.GetAtomWithIdx(site).GetNumExplicitHs() else 'pyridinic'}): "
                  f"P[S]={row[IDX_S]*100:.2f}%  top1={I2T[top][0]}{'*' if I2T[top][1] else ''}")

json.dump({'molecule': TARGET_SMI, 'pose': POSE,
           'ring_N_sites': res},
          open(OUTJSON, 'w'), indent=2)
print(f'[saved] {OUTJSON}')
